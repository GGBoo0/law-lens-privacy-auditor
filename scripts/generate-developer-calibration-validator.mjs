import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const schemaUrl = new URL(
  "../data/developer-calibration/calibration.schema.json",
  import.meta.url,
);
const outputUrl = new URL(
  "../lib/generated/developer-calibration-validator.mjs",
  import.meta.url,
);

const schema = JSON.parse(await readFile(schemaUrl, "utf8"));
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true },
});
addFormats(ajv);

const runtimeHelpers = String.raw`
// CSP-safe copies of the only external helpers used by this schema.
// Date helpers adapted from ajv-formats by Evgeny Poberezkin (MIT License):
// https://github.com/ajv-validator/ajv-formats/blob/master/LICENSE
const CALIBRATION_DATE = /^(\d\d\d\d)-(\d\d)-(\d\d)$/;
const CALIBRATION_DAYS = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
const CALIBRATION_TIME = /^(\d\d):(\d\d):(\d\d(?:\.\d+)?)(z|([+-])(\d\d)(?::?(\d\d))?)?$/i;

function calibrationDate(value) {
  const match = CALIBRATION_DATE.exec(value);
  if (!match) return false;
  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = Number(match[3]);
  const leapYear = year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
  return month >= 1 && month <= 12 && day >= 1 &&
    day <= (month === 2 && leapYear ? 29 : CALIBRATION_DAYS[month]);
}

function calibrationTime(value) {
  const match = CALIBRATION_TIME.exec(value);
  if (!match) return false;
  const hour = Number(match[1]);
  const minute = Number(match[2]);
  const second = Number(match[3]);
  const timezone = match[4];
  const timezoneSign = match[5] === "-" ? -1 : 1;
  const timezoneHour = Number(match[6] || 0);
  const timezoneMinute = Number(match[7] || 0);
  if (!timezone || timezoneHour > 23 || timezoneMinute > 59) return false;
  if (hour <= 23 && minute <= 59 && second < 60) return true;
  const utcMinute = minute - timezoneMinute * timezoneSign;
  const utcHour = hour - timezoneHour * timezoneSign - (utcMinute < 0 ? 1 : 0);
  return (utcHour === 23 || utcHour === -1) &&
    (utcMinute === 59 || utcMinute === -1) && second < 61;
}

function calibrationDateTime(value) {
  const parts = value.split(/t|\s/i);
  return parts.length === 2 && calibrationDate(parts[0]) && calibrationTime(parts[1]);
}

// Equality helper adapted from fast-deep-equal by Evgeny Poberezkin (MIT License):
// https://github.com/epoberezkin/fast-deep-equal/blob/master/LICENSE
function calibrationDeepEqual(left, right) {
  if (left === right) return true;
  if (!left || !right || typeof left !== "object" || typeof right !== "object") {
    return left !== left && right !== right;
  }
  if (left.constructor !== right.constructor) return false;
  if (Array.isArray(left)) {
    if (left.length !== right.length) return false;
    return left.every((item, index) => calibrationDeepEqual(item, right[index]));
  }
  if (left.constructor === RegExp) {
    return left.source === right.source && left.flags === right.flags;
  }
  if (left.valueOf !== Object.prototype.valueOf) return left.valueOf() === right.valueOf();
  if (left.toString !== Object.prototype.toString) return left.toString() === right.toString();
  const leftKeys = Object.keys(left);
  if (leftKeys.length !== Object.keys(right).length) return false;
  return leftKeys.every((key) =>
    Object.prototype.hasOwnProperty.call(right, key) &&
    calibrationDeepEqual(left[key], right[key]),
  );
}
`;

let generated = standaloneCode(ajv, ajv.compile(schema));
const replacements = [
  [
    /const (\w+) = require\("ajv-formats\/dist\/formats"\)\.fullFormats\["date-time"\];/,
    "const $1 = { validate: calibrationDateTime };",
  ],
  [
    /const (\w+) = require\("ajv-formats\/dist\/formats"\)\.fullFormats\.date;/,
    "const $1 = { validate: calibrationDate };",
  ],
  [
    /const (\w+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/,
    "const $1 = calibrationDeepEqual;",
  ],
];

for (const [pattern, replacement] of replacements) {
  if (!pattern.test(generated)) {
    throw new Error(`Expected standalone validator dependency was not found: ${pattern}`);
  }
  generated = generated.replace(pattern, replacement);
}

const output = `/* eslint-disable */\n// Generated by scripts/generate-developer-calibration-validator.mjs.\n// Do not edit by hand. Regenerate after changing the JSON schema.\n${runtimeHelpers}\n${generated}\n`;
if (/\brequire\s*\(|\b(?:eval|Function)\s*\(/u.test(output)) {
  throw new Error("Generated validator contains a runtime dependency or dynamic code generation");
}
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  let current;
  try {
    current = await readFile(outputUrl, "utf8");
  } catch {
    current = null;
  }
  const normalizedCurrent = current?.replace(/\r\n?/gu, "\n") ?? null;
  if (normalizedCurrent !== output) {
    throw new Error(
      `${fileURLToPath(outputUrl)} is stale. Run npm run calibration:schema:generate.`,
    );
  }
} else {
  await mkdir(dirname(fileURLToPath(outputUrl)), { recursive: true });
  await writeFile(outputUrl, output, "utf8");
}
